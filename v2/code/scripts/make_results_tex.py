def texify(s):
    """Signs and p-values in math mode (the class uses OT1, where '<' prints as an inverted !)."""
    import re
    s = str(s).replace("\u2212", "-")
    s = re.sub(r"p < (\d\.\d+)", r"$p<\1$", s)
    s = re.sub(r"p = (\d\.\d+)", r"$p=\1$", s)
    return re.sub(r"(?<![$\w-])-(?=\d)", "$-$", s)


def fmt_r(row):
    return f"{row.r:.2f} [{row.ci_low:.2f}, {row.ci_high:.2f}]"


def latest(pattern):
    runs = sorted(glob.glob(str(RESULTS / pattern)))
    return Path(runs[-1]) if runs else None


