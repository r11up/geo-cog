"""Write manuscript/results_values.tex and manuscript/results_table.tex from saved results.

Every number in the manuscript that comes from the analysis is defined here, from files
on disk; nothing is typed in by hand. Anything not yet computed stays undefined and the
manuscript shows it as a red 'pending' marker.

    ~/.venvs/urbeeg/bin/python -I scripts/make_results_tex.py
"""
import glob
import json
import sys
from pathlib import Path

CODE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(CODE))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from urbeeg.config import DERIVED, PROJECT_ROOT, RESULTS  # noqa: E402
from urbeeg.metrics import compare, summarize  # noqa: E402

MS = Path(__import__("os").environ.get("URBEEG_MS", PROJECT_ROOT / "manuscript"))
TABLE_MODELS = [
    ("intercept", "Intercept only"),
    ("scene", "Scene composition"),
    ("scene_greenery_only", "Greenery only (green view index)"),
    ("scene_lowlevel_only", "Low-level image statistics (control)"),
    ("scene+lowlevel", "Composition + low-level"),
    ("ctrl_scene_noise", "Pure-noise scene input (control)"),
    ("ctrl_scene_shuffled", "Shuffled scene input (control)"),
    ("eeg_erp4", "EEG: ERP components (P1, N1, P3, LPP)"),
    ("eeg_erpwin", "EEG: ERP time windows"),
    ("eeg_riemann", "EEG: Riemannian band covariances"),
    ("eeg", "EEG: windows + covariances"),
    ("ctrl_eeg_shuffled", "Shuffled EEG (control)"),
    ("eegnet", "EEGNet"),
    ("conformer", "EEG-Conformer"),
    ("fusion", "Fusion: scene + EEG"),
    ("ctrl_fusion_noise", "Fusion: noise + EEG (control)"),
    ("dualtower_real", "Dual-tower, scene input"),
    ("dualtower_noise", "Dual-tower, noise input (control)"),
    ("dualtower_shuffled", "Dual-tower, shuffled input (control)"),
]
TARGETS = ["valence", "arousal", "stress"]


def texify(s):
    """Signs and p-values in math mode (the class uses OT1, where '<' prints as an inverted !)."""
    import re
    s = str(s).replace("\u2212", "-")
    s = re.sub(r"p < (\d\.\d+)", r"$p<\1$", s)
    s = re.sub(r"p = (\d\.\d+)", r"$p=\1$", s)
    return re.sub(r"(?<![$\w])-(?=\d)", "$-$", s)


def fmt_r(row):
    return f"{row.r:.2f} [{row.ci_low:.2f}, {row.ci_high:.2f}]"


def latest(pattern):
    runs = sorted(glob.glob(str(RESULTS / pattern)))
    return Path(runs[-1]) if runs else None


def main():
    lines = ["% generated by scripts/make_results_tex.py -- do not edit by hand"]

    def define(kind, key, value):
        lines.append(f"\\expandafter\\def\\csname {kind}@{key}\\endcsname{{{texify(value)}}}")

    # ---- data quality (preprocessing reports)
    from urbeeg.config import EXCLUDED
    reps = [r for f in sorted((DERIVED / "eeg").glob("sub-*_report.json")) for r in json.load(open(f))
            if r["participant"] not in EXCLUDED]
    if reps:
        subs = {r["participant"] for r in reps}
        nb = np.array([len(r["bad_channels"]) for r in reps])
        ica = np.array([sum(r["ica_removed"].values()) for r in reps])
        ptp = np.array([r["n_ptp_flagged"] for r in reps])
        ntr = np.array([r["n_trials"] for r in reps])
        define("val", "nparticipants", len(subs))
        define("val", "badmedian", f"{np.median(nb):g}")
        define("val", "badmax", int(nb.max()))
        define("val", "icamedian", f"{np.median(ica):g}")
        define("val", "icamin", int(ica.min()))
        define("val", "icamax", int(ica.max()))
        define("val", "ptppct", f"{100 * ptp.sum() / ntr.sum():.1f}")
        define("val", "ntrials", int(ntr.sum()))

    frames = []
    lin = latest("linear_*")
    if lin is not None:
        frames.append(pd.read_csv(lin / "oof.csv.gz"))
        define("val", "linearrun", lin.name.replace("_", "\\_"))
    deep = sorted(glob.glob(str(RESULTS / "deep" / "*.csv.gz")))
    if deep:
        frames.append(pd.concat(pd.read_csv(f) for f in deep))
    table_rows, dev_rows = [], []
    if frames:
        oof = pd.concat(frames, ignore_index=True)
        s = summarize(oof)
        for row in s.itertuples():
            define("res", f"{row.model}@{row.target}@{row.mode}", fmt_r(row))
            define("cons", f"{row.model}@{row.target}@{row.mode}", f"{row.consensus_r:.2f}")
        for a, b in [("fusion", "scene"), ("fusion", "eeg"), ("scene", "ctrl_scene_noise"),
                     ("scene", "ctrl_scene_shuffled"), ("scene+lowlevel", "scene_lowlevel_only"),
                     ("eeg", "ctrl_eeg_shuffled"), ("fusion", "ctrl_fusion_noise"),
                     ("dualtower_real", "dualtower_noise"), ("dualtower_real", "dualtower_shuffled"),
                     *[("scene", f"scene_minus_{c}") for c in ("greenery", "buildings", "sky", "ground", "vehicles")]]:
            c = compare(oof, a, b)
            for row in c.itertuples():
                p = "p < 0.001" if row.wilcoxon_p < 1e-3 else f"p = {row.wilcoxon_p:.3f}"
                define("cmp", f"{a}@{b}@{row.target}@{row.mode}",
                       f"$\\Delta z$ = {row.mean_dz:.3f} [{row.ci_low:.3f}, {row.ci_high:.3f}], {p}")
        for model, label in TABLE_MODELS:
            cells = {}
            for mode in ("raw", "deviation"):
                cells[mode] = []
                for t in TARGETS:
                    hit = s[(s.model == model) & (s.target == t) & (s["mode"] == mode)]
                    cells[mode].append(fmt_r(hit.iloc[0]) if len(hit) else "--")
            table_rows.append(f"{label} & " + " & ".join(cells["raw"]) + r" \\")
            # personal deviation: only models that see EEG (scene-only models are 0 by construction)
            if model.startswith(("eeg", "fusion", "ctrl_eeg", "ctrl_fusion")) and any(c != "--" for c in cells["deviation"]):
                dev_rows.append(f"{label} & " + " & ".join(cells["deviation"]) + r" \\")

    # ---- Study 1 (re-run of the original design), accuracy in percent
    def pct(v):
        return f"{100 * v:.1f}"

    s1_dirs = sorted(glob.glob(str(RESULTS / "study1_2*"))) + sorted(glob.glob(str(RESULTS / "study1_singapore_*")))
    for d in s1_dirs:
        d = Path(d)
        summ = pd.read_csv(d / "summary.csv")
        for r in summ.itertuples():
            define("sone", f"{r.condition}@acc", f"{pct(r.acc)} [{pct(r.acc_lo)}, {pct(r.acc_hi)}]")
            define("sone", f"{r.condition}@f1", f"{r.f1:.3f} [{r.f1_lo:.3f}, {r.f1_hi:.3f}]")
            define("sone", f"{r.condition}@accm", pct(r.acc))
        comp = pd.read_csv(d / "comparisons.csv")
        for r in comp.itertuples():
            p_ = "p < 0.001" if r.wilcoxon_p < 1e-3 else f"p = {r.wilcoxon_p:.3f}"
            sign = "+" if r.mean_diff_acc >= 0 else "−"
            define("sonecmp", f"{r.a}@{r.b}",
                   f"{sign}{abs(100 * r.mean_diff_acc):.1f} points [{100 * r.lo:.1f}, {100 * r.hi:.1f}], {p_}")
            define("sonediff", f"{r.a}@{r.b}",       # short form for tables
                   f"{sign}{abs(100 * r.mean_diff_acc):.1f} [{100 * r.lo:.1f}, {100 * r.hi:.1f}]")
            define("sonep", f"{r.a}@{r.b}", "$<0.001$" if r.wilcoxon_p < 1e-3 else f"{r.wilcoxon_p:.3f}")
        cfg = json.load(open(d / "config.json"))
        define("val", "bandwidth", f"{cfg['bandwidth']:.3f}")
        # split-wise accuracies and paired differences
        if (d / "per_split.csv").exists() and "singapore" not in d.name:
            sp = pd.read_csv(d / "per_split.csv")
            piv = sp.pivot_table(index=["rep", "fold"], columns="condition", values="acc")
            rows = []
            for a, b, lab in [("proposed_bi", "eeg_only", "Bidirectional $-$ EEG only"),
                              ("unidirectional", "eeg_only", "Unidirectional $-$ EEG only"),
                              ("proposed_bi", "unidirectional", "Bidirectional $-$ unidirectional")]:
                if a in piv and b in piv:
                    for rep, g in (piv[a] - piv[b]).groupby(level=0):
                        vals = " & ".join(f"{100 * v:+.1f}" for v in g.to_numpy())
                        rows.append(f"{lab} & {rep + 1} & {vals} \\\\")
            (MS / "results_split_rows.tex").write_text(texify("\n".join(rows)) + "\n")
            # one-sentence summaries for the main text (no appendix)
            for a, b in [("proposed_bi", "eeg_only"), ("unidirectional", "eeg_only"),
                         ("proposed_bi", "unidirectional"), ("proposed_bi", "ctrl_matched_random"),
                         ("proposed_bi", "ctrl_noise")]:
                if a in piv and b in piv:
                    dd = 100 * (piv[a] - piv[b]).to_numpy()
                    define("split", f"{a}@{b}",
                           f"from {dd.min():+.1f} to {dd.max():+.1f} points, positive in {int((dd > 0).sum())} of {len(dd)} folds")
    # ---- sensitivity of the prior to threshold and bandwidth (simplified fusion network)
    cdirs = sorted(glob.glob(str(RESULTS / "contrast_*")))
    if cdirs:
        cs = pd.read_csv(Path(cdirs[-1]) / "summary.csv").set_index("condition")
        for q in ("0.67", "0.75", "0.90"):
            for hh in ("0.5", "1.0", "2.0"):
                key = "prior" if (q, hh) == ("0.75", "1.0") else f"prior_q{q}_h{hh}x"
                if key in cs.index:
                    define("sens", f"{q}@{hh}", pct(cs.loc[key, "acc"]))
        for c in ("eeg_only", "prior", "noise", "matched_random"):
            if c in cs.index:
                define("simple", c, pct(cs.loc[c, "acc"]))

    (MS / "results_values.tex").write_text("\n".join(lines) + "\n")
    if table_rows:
        (MS / "results_table_rows.tex").write_text(texify("\n".join(table_rows)) + "\n")
        (MS / "results_dev_rows.tex").write_text(texify("\n".join(dev_rows)) + "\n")
    print(f"wrote {len(lines) - 1} values; table rows: {len(table_rows)}")


if __name__ == "__main__":
    main()
